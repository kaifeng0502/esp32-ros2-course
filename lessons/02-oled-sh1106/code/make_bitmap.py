#!/usr/bin/env python3
"""Rasterize a message into the standalone SH1106 example; no USB access."""
import argparse
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--text',default='Hello OLED')
    p.add_argument('--subtitle',default='ESP32 + ROS2')
    p.add_argument('--font',type=Path,help='Optional font file containing the required Chinese glyphs')
    args=p.parse_args()
    font=ImageFont.truetype(str(args.font),17) if args.font else ImageFont.load_default(size=17)
    small=ImageFont.truetype(str(args.font),12) if args.font else ImageFont.load_default(size=12)
    image=Image.new('1',(128,64));draw=ImageDraw.Draw(image)
    for y,text,f in [(10,args.text,font),(40,args.subtitle,small)]:
        box=draw.textbbox((0,0),text,font=f)
        draw.text(((128-(box[2]-box[0]))//2-box[0],y-box[1]),text,font=f,fill=1)
    data=bytes(sum((1<<bit) if image.getpixel((x,page*8+bit)) else 0
                   for bit in range(8)) for page in range(8) for x in range(128))
    rows=[', '.join(f'0x{v:02x}' for v in data[i:i+16]) for i in range(0,1024,16)]
    header=Path(__file__).parent/'firmware/main/message_bitmap.h'
    header.write_text('// Generated by code/make_bitmap.py\n#pragma once\n#include <stdint.h>\n'
                      'static const uint8_t message_bitmap[1024] = {\n'+',\n'.join(rows)+'\n};\n')
    root=Path(__file__).resolve().parents[3];(root/'results').mkdir(exist_ok=True)
    image.resize((768,384),Image.Resampling.NEAREST).save(root/'results/oled-message.png')
    print(header)


if __name__=='__main__':main()
